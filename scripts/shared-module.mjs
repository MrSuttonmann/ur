// Makes worker/generated/shared.mjs: the page's pure game scripts (rules.js, then turns.js) joined as the build
// joins them and exported as a module, so the online room runs exactly the code the page does.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'worker', 'generated', 'shared.mjs');
const SCRIPTS = ['js/rules.js', 'js/turns.js'];
const EXPORTED_NAMES = [
  'SUN',
  'MOON',
  'SIDES',
  'SIDE_NAME',
  'IN_TRAY',
  'MAX_ROLL',
  'VARIANTS',
  'opponentOf',
  'legalMoves',
  'applyMove',
  'rollsAgain',
  'allHome',
  'isRose',
  'createGameStats',
  'recordMove',
  'describeMove',
];

const sources = await Promise.all(SCRIPTS.map((file) => readFile(path.join(ROOT, file), 'utf8')));
const module = [
  '// Generated by scripts/shared-module.mjs from js/rules.js and js/turns.js; do not edit.',
  sources.join('\n;\n'),
  `export { ${EXPORTED_NAMES.join(', ')} };`,
  '',
].join('\n');
await mkdir(path.dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, module);
console.log(`Wrote ${path.relative(ROOT, OUTPUT)} from ${SCRIPTS.join(' and ')}.`);
